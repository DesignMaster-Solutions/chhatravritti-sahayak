#!/usr/bin/env python3
"""Regenerates nsp-data.js from the three "Schemes on NSP" lists on scholarships.gov.in.

Run it again to refresh the dates, and change CHECKED: the app shows that date next to every deadline.
Pre-matric schemes stay out (this tool starts at Class 11). Fails loudly if the page shape changed.
"""
import html, json, pathlib, re, subprocess, sys, tempfile

CHECKED = "2026-11-14"
BASE = "https://scholarships.gov.in"
PRE = re.compile(r"pre[ -]?matric|class 1-10|class ix|class 1 to 10|class iii", re.I)


def curl(jar, *args):
    return subprocess.run(["curl", "-sSL", "-m", "60", "-A", "Mozilla/5.0", "-c", jar, "-b", jar, *args],
                          check=True, capture_output=True, text=True).stdout


def lines(page):
    s = re.sub(r"(?is)<(script|style)[^>]*>.*?</\1>", " ", page)
    s = re.sub(r'(?is)<a [^>]*href="([^"]+)"[^>]*>', r" [\1] ", s)
    s = html.unescape(re.sub(r"(?s)<[^>]+>", "\n", s))
    return [re.sub(r"\s+", " ", l).strip() for l in s.splitlines() if l.strip()]


def date(s):
    d, m, y = re.split(r"[-/]", s)
    return f"{y}-{m}-{d}"


def parse(page, kind):
    L, out, i = lines(page), [], 0
    while i < len(L) - 1:
        if L[i + 1].startswith("by ") and "Scheme" in L[i] + L[i + 1] or (L[i + 1].startswith("by ") and "(Welfare" in L[i]):
            name, by = L[i], L[i + 1][3:]
            e = {"name": name, "by": by, "kind": kind,
                 "type": "merit" if "(Merit" in name else "welfare" if "(Welfare" in name else "other"}
            j = i + 2
            while j < len(L) and j < i + 16:
                l = L[j]
                for label, key in (("Scheme Open from", "open"), ("Student Application", "close"),
                                   ("Defective Application", "defect"), ("Institute Verification", "institute"),
                                   ("DNO/SNO/MNO", "state")):
                    m = re.match(label + r"[^:]*:\s*(\d\d[-/]\d\d[-/]\d{4})", l)
                    if m:
                        e[key] = date(m.group(1))
                        if "(for Renewal)" in l:
                            e["renewalOnly"] = True
                if "NOT YET OPENED" in l:
                    e["notOpen"] = True
                m = re.match(r"\[(.*)\] (Specifications|FAQ)", l)
                if m and m.group(1) not in ("null", "") and "not_available" not in m.group(1):
                    u = m.group(1)
                    e["guide" if m.group(2) == "Specifications" else "faq"] = BASE + u if u.startswith("/") else u
                if l.endswith("] FAQ"):
                    break
                j += 1
            out.append(e)
            i = j
        i += 1
    return out


with tempfile.NamedTemporaryFile() as jar:
    central = curl(jar.name, f"{BASE}/All-Scholarships")
    tabs = {v: curl(jar.name, "-e", f"{BASE}/All-Scholarships", "-d", f"central_sponsored_state={v}",
                    f"{BASE}/centralsOrsponsoredOrstate") for v in ("sponserscheme", "statescheme")}
data = parse(central, "central") + parse(tabs["sponserscheme"], "sponsored") + parse(tabs["statescheme"], "state")
kept = [e for e in data if not PRE.search(e["name"])]
if len(kept) < 90 or not any(e["kind"] == "sponsored" for e in kept):
    sys.exit(f"NSP page shape changed: {len(data)} parsed, {len(kept)} kept")
out = pathlib.Path(__file__).parent.parent / "nsp-data.js"
out.write_text(f"// Generated by tools/nsp_snapshot.py from {BASE}/All-Scholarships. Do not edit by hand.\n"
               f"export const NSP_CHECKED = '{CHECKED}';\nexport const NSP = "
               + json.dumps(kept, ensure_ascii=False, indent=0).replace("\n", "") + ";\n")
print(len(data), "parsed;", len(kept), "kept;", out.stat().st_size, "bytes")
